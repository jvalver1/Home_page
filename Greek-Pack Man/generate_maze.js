let ok = true;
let totalDots = 0;
layout.forEach((row, i) => {
  if (row.length !== 33) {
    console.log(`Row ${i} has length ${row.length}, expected 33`);
    ok = false;
  }
  let count2 = (row.match(/2/g) || []).length;
  let count3 = (row.match(/3/g) || []).length;
  totalDots += count2 + count3;
  
  const left = row.slice(0, 16);
  const right = row.slice(17).split("").reverse().join("");
  if (left !== right) {
     console.log(`Row ${i} is not symmetrical:\nL:${left}\nR:${right}`);
     ok = false;
  }
});
